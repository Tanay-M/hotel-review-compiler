"""Use the canonical DOCX renderer with a native Word PDF conversion provider.

Windows has Word installed, but no LibreOffice. The actual DOCX is exported
by render_conference_paper.ps1; the canonical rasterizer supplies page PNGs.
"""
from pathlib import Path
import importlib.util
import os

ROOT=Path(__file__).resolve().parents[1]
SKILL=Path('C:/Users/asus/.codex/plugins/cache/openai-primary-runtime/documents/26.1025.11240/skills/documents/render_docx.py')
spec=importlib.util.spec_from_file_location('canonical_docx_renderer',SKILL)
renderer=importlib.util.module_from_spec(spec);spec.loader.exec_module(renderer)
pdf=ROOT/'output/paper/Team_17_IEEE_Conference_Paper.pdf'
if not pdf.exists():raise SystemExit('Export the actual DOCX through Word before rasterizing.')
renderer.convert_to_pdf=lambda *args,**kwargs:(str(pdf),'Native Microsoft Word 16.0 export; LibreOffice unavailable on PATH.')
paths=renderer.rasterize(str(ROOT/'output/paper/Team_17_IEEE_Conference_Paper.docx'),str(ROOT/'tmp/paper-qa-eight-pages-2026-10-27'),180,False,False)
print(f'{len(paths)} page PNGs generated by the canonical rasterizer.')
