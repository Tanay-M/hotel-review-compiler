"""Verify plotted values against saved predictions/counts; never retrain or edit scores."""
from pathlib import Path
from collections import defaultdict
from hashlib import sha256
import csv,json,math
import xml.etree.ElementTree as ET

ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/'output/paper'
SWN=ROOT/'output/experiments/2026-10-21/expanded-sentiwordnet-release/semeval-development'
DL=ROOT/'output/neural/2026-10-23-dl-pair-evaluation'


def read(p):
    with p.open(encoding='utf-8-sig',newline='') as f:return list(csv.DictReader(f))


def same(a,b):assert math.isclose(float(a),float(b),abs_tol=1e-12),(a,b)


def verify():
    sem=read(SWN/'metrics.csv');preds=read(SWN/'predictions.csv')
    labels={'Positive','Negative','Neutral'}
    for m in sem:
        rows=[r for r in preds if r['system']==m['system']]
        assert len(rows)==int(m['cases'])==148
        correct=sum(r['gold']==r['prediction'] for r in rows)
        scored=sum(r['prediction'] in labels for r in rows)
        assert correct==int(m['correct']) and scored==int(m['scored'])
        same(correct/len(rows),m['accuracy']);same(scored/len(rows),m['coverage'])
        f1=[]
        for label in labels:
            tp=sum(r['gold']==label and r['prediction']==label for r in rows)
            fp=sum(r['gold']!=label and r['prediction']==label for r in rows)
            fn=sum(r['gold']==label and r['prediction']!=label for r in rows)
            f1.append(2*tp/(2*tp+fp+fn) if 2*tp+fp+fn else 0.)
        same(sum(f1)/3,m['macro_f1'])
        tp,g,p=map(int,(m['matched_coarse_pairs'],m['gold_coarse_pairs'],m['predicted_coarse_pairs']))
        same(2*tp/(g+p),m['tuple_f1'])
    saved=read(DL/'metrics.csv');dl_preds=read(DL/'predictions.csv')
    for m in saved:
        rows=[r for r in dl_preds if r['system']==m['system'] and
              (m['scope']=='all_test' or r['routed']=='True')]
        assert len(rows)==int(m['segments'])
        gold=[set(map(tuple,json.loads(r['gold']))) for r in rows]
        predicted=[set(map(tuple,json.loads(r['prediction']))) for r in rows]
        tp=sum(len(a&b) for a,b in zip(gold,predicted));g=sum(map(len,gold));p=sum(map(len,predicted))
        assert (tp,g,p)==tuple(int(m[k]) for k in ('matched_pairs','gold_pairs','predicted_pairs'))
        same(tp/p,m['precision']);same(tp/g,m['recall']);same(2*tp/(g+p),m['pair_micro_f1'])
        same(sum(a==b for a,b in zip(gold,predicted))/len(rows),m['exact_segment_match'])
    # The companion SVG is the programmatic source of displayed bar labels.
    text=lambda name:' '.join(ET.parse(OUT/f'assets/{name}.svg').getroot().itertext())
    lexical_svg=text('performance_comparison');dl_svg=text('dl_joint_pair_f1')
    for m in sem:
        for k in ('accuracy','macro_f1','tuple_f1'):assert f'{float(m[k]):.3f}' in lexical_svg
    for m in saved:assert f'{100*float(m["pair_micro_f1"]):.2f}' in dl_svg
    definitions=[
        {'figure':1,'asset':'architecture_approved','kind':'Explanatory architecture, not a result graph',
         'generator':'scripts/build_approved_paper_architecture.py (uses build_architecture_approval.py)','evaluator':None,'data':[]},
        {'figure':2,'asset':'performance_comparison','kind':'Measured SemEval mapped development metrics',
         'generator':'scripts/paper_figures.py: charts','evaluator':'hotel_compiler/research_runner.py: evaluate_semeval',
         'data':[SWN/'metrics.csv',SWN/'predictions.csv'],'values':sem},
        {'figure':3,'asset':'dl_joint_pair_f1','kind':'Measured Trip-MA follow-up pair F1',
         'generator':'scripts/build_dl_paper_assets.py: build','evaluator':'hotel_compiler/routed_cli.py: evaluate',
         'data':[DL/'metrics.csv',DL/'predictions.csv'],'values':saved}
    ]
    for item in definitions:
        item['data']={str(p.relative_to(ROOT)).replace('\\','/'):sha256(p.read_bytes()).hexdigest() for p in item['data']}
        item['assets']={ext:sha256((OUT/f'assets/{item["asset"]}.{ext}').read_bytes()).hexdigest() for ext in ('svg','pdf','png')}
    manifest={'verified':'2026-10-27','checks':'SemEval classification recomputed from predictions; SemEval pair-F1 from saved pair counts; Trip-MA metrics recomputed from all saved gold/predicted pair sets; SVG bar labels checked against metric CSVs.',
              'model_execution':'No model training or inference was rerun for compression. Original measured outputs remain unchanged.',
              'figures':definitions}
    (OUT/'graph_provenance.json').write_text(json.dumps(manifest,indent=2),encoding='utf-8')
    report='''# Where the paper graphs come from

The performance graphs are generated by Python code reading saved experiment outputs. They are not AI illustration-tool images and their numerical values were not invented for presentation. The layout, grayscale styling and labels were written in code. The architecture is an explanatory diagram rather than an experiment result.

| Final figure | Plotting code | Data and evaluation code |
|---|---|---|
| Fig. 1 architecture | scripts/build_approved_paper_architecture.py | Approved dataset blocks, processing and training/evaluation flows; not a performance measurement |
| Fig. 2 SentiWordNet / Hybrid | scripts/paper_figures.py, charts() | output/experiments/2026-10-21/expanded-sentiwordnet-release/semeval-development/metrics.csv; evaluator: hotel_compiler/research_runner.py |
| Fig. 3 Hybrid / Hybrid + DL | scripts/build_dl_paper_assets.py, build() | output/neural/2026-10-23-dl-pair-evaluation/metrics.csv; evaluator: hotel_compiler/routed_cli.py |

SemEval accuracy/coverage/macro-F1 were independently recomputed from saved per-case predictions; pair-F1 was checked against saved integer match/prediction/gold counts. Trip-MA precision, recall, F1 and exact match were recomputed from the saved gold/predicted pair sets for all 1,474 segments and the routed 1,113 subset. Companion SVG bar labels were checked against those CSV values. graph_provenance.json stores values and SHA-256 hashes for the data and SVG/PDF/PNG assets.

The original 12-page paper also contained coverage graphs from random200/coverage.csv and booking-all/coverage.csv (scripts/paper_figures.py), class F1 from per_class_metrics.csv (the same script), validation F1 from epoch_metrics.csv (scripts/build_dl_evidence.py), and DL category F1 from per_category_comparison.csv (the same script). These were programmatic visualizations too. Their main information is retained in prose/tables in the eight-page paper; redundant plots were removed to save space.

No experiments were retrained or numerical results changed to obtain eight pages. The already inspected SemEval/Trip-MA results remain exploratory; real Booking coverage counts are not accuracy. Software contract-test fake predictions are not used as research measurements. Re-run scripts/verify_paper_graph_provenance.py to verify the numerical provenance without training a model.
'''
    (ROOT/'docs/paper-graph-provenance.md').write_text(report,encoding='utf-8')
    print('PASS: saved predictions/counts, metric CSVs and plotted SVG values agree.')
    return manifest


if __name__=='__main__':verify()
