"""Copy reviewed research inputs for Git without publishing source metadata.

Run after the existing local sampling and Booking vocabulary audit preparation.
No review wording, labels or model outputs are generated by this export.
"""
from pathlib import Path
from hashlib import sha256
import csv
import json
import shutil

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'output/datasets'
BOOKING = ROOT / 'output/experiments/2026-10-18/booking-vocabulary/inputs'


def rows(path):
    with path.open(encoding='utf-8-sig', newline='') as stream:
        reader = csv.DictReader(stream)
        return reader.fieldnames, list(reader)


def main():
    raw = BOOKING / 'original_crawlfeeds.csv'
    expected = '137cec35ddbd678b2bdb1bc93eccb2e844926c8503d3d7f898e274e387933dbd'
    assert sha256(raw.read_bytes()).hexdigest() == expected
    target = OUT / 'booking_italy'; target.mkdir(exist_ok=True)
    for source in sorted(BOOKING.glob('booking_italy_*.csv')):
        fields, _ = rows(source)
        assert fields == ['sr.no', 'review'], source
        shutil.copyfile(source, target / source.name)
        assert (target / source.name).read_bytes() == source.read_bytes()
    fields, all_rows = rows(target / 'booking_italy_all.csv')
    parts = [row for source in sorted(target.glob('booking_italy_part_*.csv')) for row in rows(source)[1]]
    assert len(all_rows) == 4367 and parts == all_rows
    assert sum(bool(r['review'].strip()) for r in all_rows) == 3102
    provenance = OUT / 'public_provenance'; provenance.mkdir(exist_ok=True)
    columns = ['sr.no', 'source_dataset', 'source_data_row', 'review_sha256', 'fields_used']
    for stem, count in [('real_hotel_demo_100', 100), ('real_hotel_random_200', 200)]:
        fields, inputs = rows(OUT / f'{stem}.csv')
        assert fields == ['sr.no', 'review'] and len(inputs) == count
        _, sources = rows(OUT / 'provenance' / f'{stem}_sources.csv')
        assert len(sources) == count
        for record, source in zip(inputs, sources):
            assert record['sr.no'] == source['sr.no']
            assert sha256(record['review'].encode()).hexdigest() == source['review_sha256']
        with (provenance / f'{stem}_sources.csv').open('w', encoding='utf-8-sig', newline='') as stream:
            writer = csv.DictWriter(stream, fieldnames=columns); writer.writeheader()
            writer.writerows({key: row[key] for key in columns} for row in sources)
    manifest = {
        'published': '2026-10-21',
        'booking_italy_source': {
            'provider': 'Crawl Feeds',
            'publisher_url': 'https://huggingface.co/datasets/crawlfeeds/Booking-Hotel-Reviews-Dataset',
            'publisher_revision': 'f39ceeede7b9d8a824909ebe88a7723ad31fa6c5',
            'publisher_bytes_match_supplied_source': True,
            'source_sha256': expected, 'license': 'CC-BY-NC-4.0',
            'source_rows': 4367, 'nonblank_bodies': 3102, 'empty_bodies_retained': 1265,
            'input_transformation': 'Retain original positive then negative body fields; omit blank/literal missing markers; join with newline. No titles or reviewer metadata.',
            'evaluation_role': 'Inspected hybrid vocabulary development; no independent aspect gold; not yet a two-system comparison.'
        },
        'excluded': ['raw source archives and reviewer metadata', 'SemEval raw XML and sentence CSV: redistribution permission not established'],
        'files': []
    }
    public = [OUT / n for n in ['real_hotel_demo_100.csv', 'real_hotel_random_200.csv', 'tripadvisor_original_20491.csv']]
    public += sorted(target.glob('*.csv')) + sorted(provenance.glob('*.csv'))
    for path in public:
        fields, records = rows(path)
        license_ = 'CC0-1.0' if path.name.startswith('real_hotel_') else 'CC-BY-NC-4.0'
        manifest['files'].append({'path': path.relative_to(ROOT).as_posix(), 'rows': len(records),
                                  'columns': fields, 'bytes': path.stat().st_size,
                                  'sha256': sha256(path.read_bytes()).hexdigest(), 'license': license_})
    (OUT / 'public_manifest.json').write_text(json.dumps(manifest, indent=2) + '\n', encoding='utf-8')
    print(f'Verified {len(public)} public CSVs; original Booking wording and all source row positions retained.')


if __name__ == '__main__':
    main()
